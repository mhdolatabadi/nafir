"""Generate rhythmo's "r" monogram mark and all shipped icon sizes.

Install rendering dependencies with `python3 -m pip install -r tool/icon-requirements.txt`,
then run `python3 tool/generate_icons.py`. Technical asset names stay stable.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKGROUND = "#0B0D16"
EMBER = "#FF626A"
VIOLET = "#8D7CFF"
# A geometric lowercase r: a rounded equalizer-bar stem and a quarter-circle
# shoulder with a round end. Two beat dots sit beside it, the lower one at
# half strength. All points lie inside the PWA maskable safe circle
# (centre 256,256; radius 204.8).
LETTER = (
    "M135 179A34 34 0 0 1 203 179V343A34 34 0 0 1 135 343Z"
    "M135 267A132 132 0 0 1 267 135A34 34 0 0 1 267 203"
    "A64 64 0 0 0 203 267Z"
)
DOT_TOP = "M313 189A32 32 0 1 0 377 189A32 32 0 1 0 313 189Z"
DOT_BOTTOM = "M313 283A32 32 0 1 0 377 283A32 32 0 1 0 313 283Z"


def icon_svg() -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">\n'
        '  <title>rhythmo</title>\n'
        f'  <rect width="512" height="512" fill="{BACKGROUND}"/>\n'
        f'  <path fill="{EMBER}" d="{LETTER}"/>\n'
        f'  <path fill="{VIOLET}" d="{DOT_TOP}"/>\n'
        f'  <path fill="{VIOLET}" fill-opacity="0.5" d="{DOT_BOTTOM}"/>\n'
        '</svg>\n'
    )


def notification_xml() -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/generate_icons.py: rhythmo r monogram. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp"\n'
        '    android:viewportWidth="512" android:viewportHeight="512">\n'
        f'  <path android:fillColor="#FFFFFFFF" android:pathData="{LETTER}"/>\n'
        f'  <path android:fillColor="#FFFFFFFF" android:pathData="{DOT_TOP}"/>\n'
        f'  <path android:fillColor="#FFFFFFFF" android:fillAlpha="0.5"\n'
        f'      android:pathData="{DOT_BOTTOM}"/>\n'
        '</vector>\n'
    )


def main() -> None:
    import cairosvg

    svg = icon_svg()
    (ROOT / 'web/icons/icon.svg').write_text(svg, encoding='utf-8')
    (ROOT / 'android/app/src/main/res/drawable/ic_stat_nafir.xml').write_text(
        notification_xml(), encoding='utf-8'
    )
    targets = {'assets/icon/nafir.png': 288,
               'server/internal/httpapi/public/nafir.png': 288,
               'web/icons/icon-192.png': 192, 'web/icons/icon-512.png': 512}
    for density, size in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96),
                          ('xxhdpi', 144), ('xxxhdpi', 192)]:
        targets[f'android/app/src/main/res/mipmap-{density}/ic_launcher.png'] = size
    for path, size in targets.items():
        cairosvg.svg2png(bytestring=svg.encode(), write_to=str(ROOT / path),
                        output_width=size, output_height=size)


if __name__ == '__main__':
    main()
